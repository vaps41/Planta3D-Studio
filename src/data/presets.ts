/**
 * Constrói um documento de planta completo aplicando cálculo automático de áreas,
 * auto-decoração sem colisão e imagem de planta baixa técnica.
 */
function finalizePresetDocument(doc: FloorPlanDocument): FloorPlanDocument {
  const roomsWithArea = doc.rooms.map((r) => ({
    ...r,
    areaSqm: computePolygonAreaSqm(r.polygon),
  }));
  const autoFurniture = autoFurnishFloorPlan(
    roomsWithArea,
    doc.walls,
    doc.openings
  );
  const fullDoc: FloorPlanDocument = {
    ...doc,
    rooms: roomsWithArea,
    furniture: autoFurniture,
  };
  fullDoc.sourceImageDataUrl = generateBlueprintDataUrlFromDocument(fullDoc);
  return fullDoc;
}

